/** Тип поля формы. Определяет и орган ввода, и вид значения в документе. */
export type FieldKind =
  | 'text'
  | 'textarea'
  | 'date'
  | 'money'
  | 'number'
  | 'employee'
  | 'counterparty'
  | 'select';

/** Описание одного поля (аналог записи в fields.yaml). */
export interface FieldDef {
  id: string;
  kind: FieldKind;
  label: string;
  /** Пояснение под полем: что именно сюда вписывают. */
  hint?: string;
  required: boolean;
  /** Варианты для kind: 'select'. */
  options?: string[];
  /** Единица измерения справа в поле: «₸», «дней». */
  unit?: string;
  /** Группа полей на форме: поля одной группы стоят рядом под общим заголовком. */
  group: string;
  /**
   * Для kind: 'date'. Ограничения задаются данными шаблона, а не кодом формы:
   * «дата возвращения не раньше даты выезда» — это свойство приказа о
   * командировке, а не общее правило для всех дат.
   */
  dateLimits?: DateLimits;
  /**
   * Как писать дату в документе.
   *
   * `long` – прописью на языке колонки: «2026 жылғы 24 тамызындағы»,
   * «24 августа 2026», «August 24, 2026». Так в документах группы написана
   * дата решения участников. По умолчанию дата идёт числами.
   */
  dateStyle?: 'long';
  /**
   * Значение по умолчанию берётся из реквизитов компании: «@company.directorBasis».
   * Человек его видит и может поправить, но начинать с пустого поля незачем —
   * пропуск в документе выглядит как потерянный реквизит.
   */
  defaultFrom?: string;
  /**
   * Значение пишется на каждом языке документа отдельно.
   *
   * Документ выходит в три колонки, и живой текст — должность, цель поездки,
   * число прописью — в каждой колонке свой. Переводить его на лету нельзя,
   * поэтому форма показывает столько полей, сколько языков у шаблона.
   *
   * Русское значение лежит под своим идентификатором, остальные — под
   * «id.kk» и «id.en». Пустой перевод заменяется русским: пропуск в приказе
   * читается как потерянный реквизит, а видимый русский текст сразу
   * показывает, что перевода нет.
   */
  perLang?: boolean;
}

/** Ограничения даты. Проверяются и в органе ввода, и при сохранении. */
export interface DateLimits {
  /** Дата не раньше значения этого поля: 'from' у даты возвращения. */
  afterField?: string;
  /** Дата не раньше сегодняшнего дня: приказ задним числом недействителен. */
  notBefore?: 'today';
  /** Дата не позже сегодняшнего дня: договор не может быть подписан завтра. */
  notAfter?: 'today';
}

/**
 * Кусок текста документа: либо постоянный текст, либо подстановка поля.
 *
 * `fallback` нужен переводам: должность в казахской колонке берётся из поля
 * `positionKk`, а пока его не заполнили – из русского `position`. Пустое
 * место в приказе выглядит как потерянный реквизит, а видимая русская
 * должность сразу показывает, что перевода нет.
 */
export type Run =
  | { text: string; bold?: boolean }
  | {
      field: string;
      fallback?: string;
      bold?: boolean;
      /**
       * Текст по значению поля, а не само значение.
       *
       * Нужен там, где выбор в форме меняет формулировку: статья Трудового
       * кодекса в приказе о расторжении зависит от основания – по инициативе
       * работника одна, в остальных случаях другая. Не нашлось значения в
       * таблице – ставится `otherwise`.
       */
      map?: Record<string, string>;
      otherwise?: string;
    };

/** Абзац: последовательность кусков. */
export type Para = Run[];

/**
 * Язык документа.
 *
 * Это не язык интерфейса. Приказ в Казахстане выпускается на казахском и
 * русском сразу, в одном листе, колонка к колонке; английская колонка нужна
 * компаниям с иностранным участием и работникам-нерезидентам.
 */
export type DocLang = 'kk' | 'ru' | 'en';

/** Постоянная надпись на трёх языках: «Б Ұ Й Р Ы Қ / ПРИКАЗ / ORDER». */
export type TriText = Record<DocLang, string>;

/**
 * Строка таблицы документа: свои абзацы на каждом языке.
 *
 * Поля (`{ field }`) в колонках одни и те же — значение у них общее. Разным
 * будет только постоянный текст вокруг них.
 *
 * Языки перечислены не все: сколько колонок печатать, решает `langs` самого
 * шаблона. Пока перевода нет, строка заполнена одним языком, и тело выходит
 * в одну колонку во всю ширину — бланк при этом тот же.
 */
export type TriRow = Partial<Record<DocLang, Para[]>>;

/** Строка двуязычной таблицы: доверенность выпускается на русском и английском. */
export type BiRow = { ru: Para[]; en: Para[] };

/**
 * Блок документа. Из блоков собирается лист.
 *
 * Первая группа — бланк приказа по образцу настоящих документов группы:
 * логотип, трёхстрочное наименование, город и дата, заголовок с номером,
 * таблицы в три колонки, подпись и лист ознакомления.
 *
 * Вторая группа — простой одноязычный лист. На нём пока стоят документы,
 * для которых нет проверенного казахского и английского текста: выдумывать
 * юридические формулировки нельзя (CLAUDE.md, п. 4.9).
 */
export type DocBlock =
  // ── Бланк приказа ──────────────────────────────────────────────────────
  /** Логотип компании и её наименование на трёх языках. */
  | { kind: 'letterhead' }
  /** Город слева, дата справа. Город печатается на трёх языках через косую. */
  | { kind: 'place-date' }
  /** «Б Ұ Й Р Ы Қ / ПРИКАЗ / ORDER № 51-26-ЛС» вразрядку по центру. */
  | { kind: 'order-title'; words: TriText }
  /** «Б Ұ Й Ы Р А М Ы Н / П Р И К А З Ы В А Ю / IT IS HEREBY ORDERED:». */
  | { kind: 'tri-line'; words: TriText }
  /** Таблица в три колонки без линий: казахский, русский, английский. */
  | { kind: 'tri-table'; rows: TriRow[] }
  /** Подпись руководителя: должность на трёх языках, ФИО кириллицей и латиницей. */
  | { kind: 'tri-signature' }
  /** Лист ознакомления на трёх языках. */
  | { kind: 'tri-acquaint' }
  /** «Исполнен»: кто подготовил документ и как с ним связаться. */
  | { kind: 'executor'; runs: Para }
  // ── Бланк доверенности ─────────────────────────────────────────────────
  /** Заголовок доверенности: номер, место и дата выдачи, на двух языках. */
  | { kind: 'poa-title'; words: { ru: string; en: string } }
  /** Таблица в две колонки: русский и английский. */
  | { kind: 'bi-table'; rows: BiRow[] }
  /** Подпись под доверенностью: черта, должность и компания по центру. */
  | { kind: 'poa-signature' };

/** Шаблон документа: описание формы и самого листа. */
export interface DocumentTemplate {
  id: string;
  title: string;
  /** Раздел, которому документ принадлежит: по нему проверяется право. */
  sectionId: string;
  subsectionId: string;
  /** Серия номера (catalog/series.yaml). */
  series: string;
  profile: 'standard' | 'sensitive' | 'policy' | 'register' | 'self-service' | 'external';
  /** Краткое объяснение, когда этот документ нужен. */
  purpose: string;
  /**
   * Проверен ли текст юристом. Пока false — интерфейс показывает пометку,
   * чтобы черновик текста не ушёл в дело как готовый (CLAUDE.md, п. 4.9).
   */
  reviewed: boolean;
  /**
   * Вид бланка.
   *
   * `order` — бланк приказа группы: логотип, наименование на трёх языках,
   * город и дата, заголовок с номером, тело в колонках, подпись с чертой,
   * лист ознакомления. `poa` — доверенность: две колонки и подпись по центру.
   *
   * Прежнего одноязычного листа больше нет: оформление одинаково у всех
   * документов, а число колонок в теле задаёт `langs`.
   */
  layout: 'order' | 'poa';
  /**
   * Языки, на которых текст этого шаблона действительно написан.
   *
   * Он же задаёт число колонок в теле. Пока перевода нет, документ выходит
   * на том же бланке, но в одну колонку, и интерфейс говорит об этом прямо:
   * молча показывать одноязычный приказ как готовый нельзя — его подадут
   * в дело.
   */
  langs: DocLang[];
  fields: FieldDef[];
  body: DocBlock[];
}

/**
 * Строка каталога «Создать документ».
 *
 * Документ из списка заказчика может ещё не иметь шаблона. Показываем его
 * всё равно: человек должен видеть, что документ в системе учтён, а не
 * гадать, почему его нет.
 */
export interface CatalogEntry {
  id: string;
  title: string;
  sectionId: string;
  subsectionId: string;
  /** ready — шаблон заполнен и документ можно создать; soon — шаблон готовится. */
  state: 'ready' | 'soon';
}

/**
 * Состояние документа.
 *
 * Состояний два. Согласование и утверждение убраны по прямому указанию
 * человека: в группе документ заполняет тот, кто за него отвечает, и лишний
 * круг визирования только задерживает бумагу. Жизненный цикл из
 * `docs/architecture.md`, п. 7 к этому вернётся, когда согласование
 * действительно понадобится.
 */
export type DocumentStatus = 'draft' | 'saved';

/** Созданный документ. */
export interface DocumentRecord {
  id: string;
  templateId: string;
  companyId: string;
  title: string;
  /**
   * Пояснение для реестра: чем этот документ отличается от соседних.
   * Заполняется по желанию и в сам документ не попадает – в приказе нет
   * места для заметки делопроизводителя.
   */
  description: string;
  /**
   * Для кого документ: ФИО работника, о котором он составлен. Спрашивается
   * при создании и виден в реестре. Пусто у документов, которые ни о ком
   * конкретно не составлены.
   */
  subject: string;
  status: DocumentStatus;
  /** Номер вводится вручную и может отсутствовать. */
  number: string | null;
  createdAt: string;
  /** Когда запись меняли последний раз: черновик правится, а не создаётся заново. */
  updatedAt: string;
  /** Снимок значений полей: изменение справочника его не меняет. */
  values: Record<string, string>;
  /**
   * Снимок реквизитов компании на момент сохранения.
   *
   * Без него смена директора или адреса переписала бы уже выпущенные
   * приказы задним числом (CLAUDE.md, п. 3.4). У черновика снимка нет:
   * он показывает текущие реквизиты, потому что ещё не выпущен.
   */
  companySnapshot?: Company;
  /**
   * Снимок карточек людей, на которых документ ссылается.
   *
   * В `values` работник лежит идентификатором. Без этого снимка исправление
   * фамилии в справочнике переписало бы уже выпущенный приказ, а удаление
   * карточки оставило бы в тексте идентификатор вместо фамилии. Ключ —
   * идентификатор работника.
   */
  peopleSnapshot?: Record<string, EmployeeBrief>;
  /** Кто заполнил: идентификатор нужен, чтобы работник видел только свои. */
  authorId: string;
  authorName: string;
  /** Документ скрыт из реестров. Физического удаления нет (CLAUDE.md, п. 3.4). */
  deletedAt?: string;
  deletedBy?: string;
}

/** Роль. Роль – это набор прав, а не константа в коде (CLAUDE.md, п. 3.2). */
export type RoleId = 'platform-admin' | 'director' | 'employee';

/** Действие, на которое проверяется право. */
export type Action =
  | 'admin.panel'
  | 'company.create'
  | 'company.edit'
  | 'people.manage'
  | 'documents.viewAll'
  | 'documents.editAny'
  | 'documents.delete'
  | 'audit.view';

export interface Role {
  id: RoleId;
  title: string;
  /** platform – все компании; company – только своя. */
  scope: 'platform' | 'company';
  description: string;
  /** Права роли. Пустой список – прав нет вовсе. */
  can: Action[];
}

/** Учётная запись. Пароля здесь нет: он лежит только хешем. */
export interface User {
  id: string;
  login: string;
  displayName: string;
  role: RoleId;
  /**
   * Компании, в которых у человека есть доступ. У администратора платформы
   * список пуст – он работает во всех.
   */
  companyIds: string[];
  /**
   * Разделы каталога, в которых человеку разрешено создавать документы –
   * «юрисдикция». Пустой список у директора и администратора означает
   * «все разделы»; у работника – ни одного, по умолчанию запрещено.
   */
  sectionIds: string[];
  /** Карточка работника в справочнике, если человек состоит в штате. */
  employeeId?: string;
  position?: string;
  phone?: string;
  email?: string;
  /** Аватар: изображение в data:URL, заполняет сам человек. */
  avatar?: string;
  /** Учётная запись заблокирована администратором. */
  blocked?: boolean;
  createdAt: string;
}

/** Запись журнала действий: кто, что и когда. */
export interface AuditEntry {
  id: string;
  at: string;
  userId: string;
  userName: string;
  companyId: string;
  /** Что произошло: 'document.create', 'user.create', 'company.edit'. */
  event: string;
  /** О чём запись: заголовок документа, логин пользователя. */
  target: string;
}

/** Настройки платформы. Правит только администратор. */
export interface PlatformSettings {
  /**
   * Адреса, с которых разрешён вход в админ-панель.
   *
   * Браузер своего внешнего адреса не знает, и проверить это на сайте
   * нельзя – список хранится как настройка, а исполняет её сервер
   * (TODO(phase-01): проверка IP в middleware).
   */
  adminIpAllowList: string[];
}
