/** Банковский счёт компании. Счетов обычно несколько: тенговый и валютные. */
export interface BankAccount {
  /** ИИК (IBAN). */
  iban: string;
  /** Валюта счёта: KZT, USD, EUR. */
  currency: string;
}

/** Банковские реквизиты: нужны в договорах, счетах и платёжных документах. */
export interface BankDetails {
  /** Наименование банка, как оно пишется в реквизитах. */
  name: string;
  bik: string;
  accounts: BankAccount[];
}

/**
 * Свидетельство о постановке на учёт по НДС.
 *
 * Печатается в счетах на оплату и счетах-фактурах: покупателю нужно видеть,
 * что продавец — плательщик НДС, и по какому свидетельству.
 */
export interface VatCertificate {
  series: string;
  number: string;
  /** Дата выдачи: в реквизитах её часто не присылают. */
  issuedAt?: string;
}

/**
 * Головной офис за рубежом.
 *
 * У компании с иностранным участием он стоит на бланке рядом с казахстанским
 * адресом, поэтому хранится вместе с реквизитами, а не в заметках.
 */
export interface HeadOffice {
  address: string;
  phone?: string;
  email?: string;
  /** Итальянская сертифицированная почта: для официальной переписки. */
  pec?: string;
}

/** Налоговый орган по месту регистрации: нужен в налоговых формах и ЭСФ. */
export interface TaxOffice {
  /** Наименование управления, как оно пишется в документах. */
  name: string;
  /** БИН самого органа. */
  bin: string;
}

/** Компания группы: реквизиты и брендинг. */
export interface Company {
  id: string;
  /** Краткое наименование для интерфейса: «ТОО «ExLumen»». */
  name: string;
  /** Полное наименование для документов. */
  legalName: string;
  /** Наименование на английском: нужно в двуязычных документах и договорах с нерезидентами. */
  legalNameEn?: string;
  /**
   * Полное наименование на казахском.
   *
   * В шапке приказа три строки подряд: казахская, русская, английская.
   * Перевод не вычисляется — организационно-правовая форма пишется по уставу
   * («ЖАУАПКЕРШІЛІГІ ШЕКТЕУЛІ СЕРІКТЕСТІК» у ТОО, «ПАРТНЕРСТВО…» у ПОО),
   * и ошибка здесь стоит на первой строке каждого документа.
   */
  legalNameKk?: string;
  bin: string;
  /** Юридический адрес без индекса: индекс хранится отдельно. */
  address: string;
  /** Юридический адрес на английском. */
  addressEn?: string;
  /**
   * Фактический адрес, если отличается от юридического. В документ идёт
   * юридический, а этот — для корреспонденции и шапки бланка.
   */
  actualAddress?: string;
  /** Почтовый индекс: в шапке бланка он стоит перед адресом. */
  postalCode?: string;
  /** КБе — код бенефициара, нужен в платёжных документах. */
  kbe?: string;
  phone?: string;
  email?: string;
  website?: string;
  bank?: BankDetails;
  taxOffice?: TaxOffice;
  vat?: VatCertificate;
  headOffice?: HeadOffice;
  /** Руководитель: он подписывает документы. */
  directorName: string;
  /**
   * Подпись руководителя: фамилия и инициалы.
   *
   * В документах группы под чертой стоит «Ихсанова С.Т.», а не полное имя.
   * Сокращение хранится, а не вычисляется: инициалы из «Самал Кабешова»
   * программно не собрать – там не видно, где фамилия, а где имя.
   */
  directorNameShort?: string;
  directorTitle: string;
  /**
   * Должность руководителя на казахском и английском.
   *
   * В подписи под приказом должность стоит столбиком на трёх языках:
   * «Бас директор / Генеральный директор / General Director». Не переводится
   * на лету: название должности берётся из устава и приказа о назначении.
   */
  directorTitleKk?: string;
  directorTitleEn?: string;
  /**
   * Должность и ФИО руководителя в родительном падеже: «в лице Директора
   * Сагинова Ерлана Жанатовича». Хранятся отдельно, потому что склонять
   * фамилии программно нельзя — на казахских и составных фамилиях это
   * даёт ошибки прямо в тексте документа.
   */
  directorTitleGenitive: string;
  directorNameGenitive: string;
  /** ФИО руководителя латиницей: подпись в английской версии документа. */
  directorNameEn?: string;
  /** Основание полномочий: «на основании Устава». */
  directorBasis: string;
  city: string;
  /** Город на казахском: «Ақсай». В шапке он идёт первым. */
  cityKk?: string;
  /**
   * Город латиницей ровно так, как он печатается: «Astana city», «Aksai».
   * Слово «city» не дописывается кодом – в документах группы оно стоит не
   * везде, и это свойство самого бланка компании.
   */
  cityEn?: string;
  /** Цвет компании: подменяет --accent после входа. */
  accent: string;
  /** Буквы для знака компании, пока не загружен логотип. */
  monogram: string;
  /**
   * Печатать ли строку «Жұмыс беруші / Работодатель / Employer:» над подписью.
   *
   * Она есть не во всех бланках группы: в приказах Kazakhstan New Technologies
   * стоит, в приказах GREENSPARKLIMITED и Algoritmi KZ – нет.
   */
  employerCaption?: boolean;
  /**
   * Логотип на бланке: изображение в data:URL.
   *
   * В настоящих документах группы он стоит в колонтитуле слева. Пока логотипа
   * нет, его место занимают буквы из `monogram`.
   */
  logo?: string;
  /**
   * Реквизиты вымышленные, компания заведена для примера. Интерфейс это
   * показывает: документ с ненастоящим БИН подписывать нельзя, и человек
   * должен видеть разницу до того, как начнёт заполнять.
   */
  placeholder?: boolean;
}

